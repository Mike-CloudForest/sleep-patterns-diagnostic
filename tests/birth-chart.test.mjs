test('invalid calendar dates, future dates, invalid times and invalid zones reject clearly', () => {
  assert.throws(() => chart(details('2001-02-29')), codeIs('invalid_birth_date'));
  assert.throws(() => chart(details('1899-12-31')), codeIs('invalid_birth_date'));
  assert.throws(() => chart(details('2027-01-01')), codeIs('future_birth_date'));
  assert.throws(() => chart(details('2000-01-01', '24:00')), codeIs('invalid_birth_time'));
  assert.throws(() => chart(details('2000-01-01', '12:60')), codeIs('invalid_birth_time'));
  assert.throws(() => chart(details('2000-01-01', '12:00', 'Fake/Time_Zone')), codeIs('invalid_time_zone'));
  assert.throws(() => chart({ ...details(), timeAccuracy: 'guessed' }), codeIs('invalid_time_accuracy'));
  assert.throws(() => chart({ ...details(), timeOccurrence: 'middle' }), codeIs('invalid_time_occurrence'));
});

test('manual birthplace with known IANA zone needs no invented coordinates', () => {
  const input = details();
  const expected = chart(input);
  assert.deepEqual(chart({ ...input, place: { ...input.place, latitude: 50.85, longitude: 4.35 } }), expected);
  assert.throws(() => chart({ ...input, place: { ...input.place, latitude: 50.85 } }), codeIs('invalid_birth_place'));
  assert.throws(() => chart({ ...input, place: { ...input.place, latitude: 91, longitude: 4.35 } }), codeIs('invalid_birth_place'));
  assert.throws(() => chart({ ...input, place: { ...input.place, label: '' } }), codeIs('invalid_birth_place'));
});

test('chart output is deterministic and excludes raw birth and unsupported sub-line details', () => {
  const input = details();
  const result = chart(input);
  assert.deepEqual(chart(input), result);
  assert.deepEqual(Object.keys(result).sort(), ['humanDesign', 'precision', 'version', 'warnings', 'western']);
  const json = JSON.stringify(result);
  for (const value of [input.date, input.time, input.place.label, input.place.timeZone]) assert.equal(json.includes(value), false);
  for (const stream of Object.values(result.humanDesign.activations)) {
    assert.equal(stream.length, 13);
    for (const activation of stream) assert.deepEqual(Object.keys(activation), ['body', 'gate', 'line']);
  }
});

function fromGates(gates) {
  const list = gates.length ? gates : [1];
  return deriveHumanDesign({
    personality: list.map((gate, i) => ({ body: i === 0 ? 'sun' : 'moon', gate, line: 1 })),
    design: [{ body: 'sun', gate: list[0], line: 3 }]
  });
}

test('BodyGraph rules cover all types and prioritize emotional before sacral authority', () => {
  assert.equal(fromGates([1]).type, 'reflector');
  assert.equal(fromGates([1]).authority, 'lunar');
  assert.equal(fromGates([5, 15]).type, 'generator');
  assert.equal(fromGates([5, 15]).authority, 'sacral');
  assert.equal(fromGates([20, 34]).type, 'manifesting_generator');
  assert.equal(fromGates([21, 45]).type, 'manifestor');
  assert.equal(fromGates([4, 63]).type, 'projector');
  assert.equal(fromGates([6, 59]).authority, 'emotional');
});

test('motor-to-throat can cross several channels or be separate from the sacral component', () => {
  assert.equal(fromGates([21, 45, 5, 15]).type, 'manifesting_generator');
  assert.equal(fromGates([51, 25, 1, 8]).type, 'manifestor');
  assert.equal(fromGates([51, 25, 1, 8]).authority, 'ego_manifested');
});

test('less common authorities follow the defined connections', () => {
  assert.equal(fromGates([18, 58]).authority, 'splenic');
  assert.equal(fromGates([21, 45]).authority, 'ego_manifested');
  assert.equal(fromGates([25, 51]).authority, 'ego_projected');
  assert.equal(fromGates([1, 8]).authority, 'self_projected');
  assert.equal(fromGates([4, 63]).authority, 'environmental');
});

test('definition counts connected components rather than channels', () => {
  assert.equal(fromGates([1]).definition, 'none');
  assert.equal(fromGates([1, 8, 13, 33]).definition, 'single');
  assert.equal(fromGates([1, 8, 4, 63]).definition, 'split');
  assert.equal(fromGates([1, 8, 4, 63, 18, 58]).definition, 'triple_split');
  assert.equal(fromGates([1, 8, 4, 63, 18, 58, 37, 40]).definition, 'quadruple_split');
});

