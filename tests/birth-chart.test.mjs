test('changing the birth time changes the actual planetary activations', () => {
  assert.notDeepEqual(chart(details('1990-06-06', '00:00')).humanDesign.activations,
    chart(details('1990-06-06', '12:00')).humanDesign.activations);
});

test('design moment solves an 88-degree solar arc across the zodiac seam', () => {
  const moment = resolve(details('1990-04-01', '12:00', 'UTC'));
  const engine = createAstronomyEngine();
  const designJD = findDesignJD(moment.julianDay, jd => engine.sunLongitude(jd));
  const arc = (engine.sunLongitude(moment.julianDay) - engine.sunLongitude(designJD) + 360) % 360;
  assert.ok(Math.abs(arc - 88) < 0.00002);
  assert.ok(moment.julianDay - designJD > 80 && moment.julianDay - designJD < 100);
  assert.ok(Math.abs(moment.julianDay - designJD - 88) > 0.25, 'must not substitute 88 calendar days');
});

test('gate and line mapping uses the standard 223.25-degree wheel start', () => {
  const atStart = longitudeToActivation(223.25);
  const beforeStart = longitudeToActivation(223.25 - 0.000001);
  assert.equal(atStart.g, 1); assert.equal(atStart.l, 1);
  assert.equal(beforeStart.g, 44); assert.equal(beforeStart.l, 6);
  assert.equal(longitudeToActivation(268.25).g, 10);
  assert.equal(longitudeToActivation(268.25 - 0.000001).g, 11);
  assert.deepEqual(longitudeToActivation(-136.75), atStart);
});

